import { chromium } from "playwright"
import assert from "node:assert/strict"

const browser = await chromium.launch({ headless: true, executablePath: "/root/PeiXianDB/.tooling/browsers/chromium_headless_shell-1208/chrome-headless-shell-linux64/chrome-headless-shell" })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on("pageerror", (error) => errors.push(error.message))
await page.goto("http://127.0.0.1:4174/dev/graph-preview", { waitUntil: "networkidle" })
await page.waitForTimeout(1800)
assert.equal(await page.locator("h1").first().textContent(), "实体关系图谱")
assert.equal(await page.locator(".entity-graph-canvas").count(), 1)
assert.ok(await page.locator(".entity-graph-stage canvas").count() > 0)
assert.equal(await page.locator(".graph-load-error").count(), 0)
await page.evaluate(() => { window.__originalGraphCanvas = document.querySelector(".entity-graph-stage canvas") })
const bounds = await page.locator(".entity-graph-canvas").boundingBox()
assert.ok(bounds)
const x = bounds.x + bounds.width * 0.464
const y = bounds.y + bounds.height * 0.46
await page.mouse.move(x, y)
await page.waitForTimeout(250)
assert.equal(await page.locator(".graph-entity-card").count(), 1)
assert.match(await page.locator(".graph-entity-card").textContent(), /实体类型：/)
await page.screenshot({ path: "/tmp/peixian-graph-hover.png", fullPage: true })
await page.mouse.click(x, y)
assert.equal(await page.locator(".graph-detail").count(), 1)
await page.mouse.move(x, y)
await page.mouse.down()
await page.mouse.move(x + 38, y + 24, { steps: 8 })
await page.mouse.up()
await page.mouse.wheel(0, -250)
await page.getByRole("button", { name: /适配/ }).click()
await page.getByRole("button", { name: "高亮路径" }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: "/tmp/peixian-graph-path.png", fullPage: true })
assert.equal(await page.evaluate(() => window.__originalGraphCanvas === document.querySelector(".entity-graph-stage canvas")), true)
await page.getByRole("combobox", { name: "筛选节点类型" }).selectOption("vehicle")
await page.waitForTimeout(250)
assert.equal(await page.evaluate(() => window.__originalGraphCanvas === document.querySelector(".entity-graph-stage canvas")), true)
assert.deepEqual(errors, [])
const production = await browser.newPage()
await production.goto("http://127.0.0.1:4175/dev/graph-preview", { waitUntil: "networkidle" })
assert.equal(await production.locator("h1").textContent(), "404")
assert.equal(await production.locator(".entity-graph-canvas").count(), 0)
console.log(JSON.stringify({ hover: true, click: true, drag: true, zoom: true, fitView: true, path: true, filter: true, stableCanvas: true, productionPreviewDisabled: true, errors }))
await page.screenshot({ path: "/tmp/peixian-graph-preview.png", fullPage: true })
await browser.close()
